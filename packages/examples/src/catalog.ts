import { Schema } from 'effect'

export const CategoryStatus = Schema.Literals(['published', 'planned'])
export type CategoryStatus = typeof CategoryStatus.Type

/** `unstable` modules may change in a minor Effect release. */
export const Stability = Schema.Literals(['stable', 'unstable'])
export type Stability = typeof Stability.Type

export const Category = Schema.Struct({
  id: Schema.String,
  title: Schema.String,
  blurb: Schema.String,
  status: CategoryStatus,
  stability: Stability,
  /** Effect modules this category is responsible for demonstrating. */
  modules: Schema.Array(Schema.String),
  slugs: Schema.Array(Schema.String),
})
export type Category = typeof Category.Type

/** A category is published once it has examples, and planned until then. */
const topic = (
  id: string,
  title: string,
  blurb: string,
  stability: Stability,
  modules: ReadonlyArray<string>,
  slugs: ReadonlyArray<string> = [],
): Category => ({
  id,
  title,
  blurb,
  status: slugs.length > 0 ? 'published' : 'planned',
  stability,
  modules,
  slugs,
})

